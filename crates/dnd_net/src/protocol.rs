//! Messages exchanged between clients and the authoritative host.

use dnd_session::Command;
use dnd_session::event::Event;
use dnd_session::model::Principal;
use dnd_session::view::ClientView;
use futures::{SinkExt, StreamExt};
use serde::{Deserialize, Serialize};
use tokio::net::TcpStream;
use tokio_util::codec::{Framed, LengthDelimitedCodec};

/// Bumped on any incompatible change to messages or game-state views.
pub const PROTOCOL_VERSION: u32 = 1;
/// Max frame: a 4 MB portrait hex-encoded is ~8 MB.
pub const MAX_FRAME: usize = 12 * 1024 * 1024;

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Hello {
    pub protocol: u32,
    pub app_version: String,
    pub session_code: String,
    pub name: String,
    /// Returned in `Welcome`; lets a disconnected player reclaim their seat and character.
    pub resume_token: Option<String>,
    /// Only the DM's own client knows this (generated by the host at startup).
    pub dm_secret: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum HostRequest {
    Save { label: String },
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum ClientMsg {
    Hello(Hello),
    Cmd { seq: u64, command: Command },
    Host { seq: u64, request: HostRequest },
    GetAsset { hash: String },
    Ping { t: u64 },
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum ServerMsg {
    Welcome { you: Principal, resume_token: String, campaign: String },
    Rejected { reason: String },
    View(Box<ClientView>),
    Events(Vec<Event>),
    CmdResult { seq: u64, error: Option<String> },
    Asset {
        hash: String,
        #[serde(with = "dnd_session::hexbytes")]
        bytes: Vec<u8>,
    },
    Pong { t: u64 },
}

pub type Wire = Framed<TcpStream, LengthDelimitedCodec>;

pub fn framed(stream: TcpStream) -> Wire {
    let codec = LengthDelimitedCodec::builder().max_frame_length(MAX_FRAME).new_codec();
    Framed::new(stream, codec)
}

#[derive(Debug, thiserror::Error)]
pub enum WireError {
    #[error("io: {0}")]
    Io(#[from] std::io::Error),
    #[error("malformed message: {0}")]
    Json(#[from] serde_json::Error),
    #[error("connection closed")]
    Closed,
}

pub async fn send<T: Serialize>(w: &mut Wire, msg: &T) -> Result<(), WireError> {
    let bytes = serde_json::to_vec(msg)?;
    w.send(bytes::Bytes::from(bytes)).await?;
    Ok(())
}

pub async fn recv<T: for<'de> Deserialize<'de>>(w: &mut Wire) -> Result<T, WireError> {
    match w.next().await {
        Some(Ok(frame)) => Ok(serde_json::from_slice(&frame)?),
        Some(Err(e)) => Err(e.into()),
        None => Err(WireError::Closed),
    }
}
